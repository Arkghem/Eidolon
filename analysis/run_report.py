"""Collect every experiment's recorded metrics into one markdown table.

Usage
-----
    python analysis/run_report.py
    python analysis/run_report.py --out out/report.md

Inputs (whatever exists is used; missing pieces are skipped, not fatal):
    experiments/*/results/*.json          metrics written by metrics.py
    experiments/*/results/compare/metrics.json   aggregated by compare.py
    experiments/*/README.md               the question each experiment asks

The point is a single place that answers "which experiments have numbers, and
what are they" without opening 20 directories.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


def experiment_title(readme: Path) -> str:
    if not readme.is_file():
        return ""
    # utf-8-sig: tolerate a BOM, which Windows editors (and PowerShell 5.1's
    # Set-Content -Encoding UTF8) happily add. Without this the first heading
    # silently stops matching.
    for line in readme.read_text(encoding="utf-8-sig", errors="replace").splitlines():
        line = line.strip()
        if line.startswith("# "):
            return line[2:].strip()
    return ""


def gather(repo_root: Path) -> list[dict]:
    rows = []
    exp_root = repo_root / "experiments"
    if not exp_root.is_dir():
        return rows
    for exp in sorted(p for p in exp_root.iterdir() if p.is_dir() and not p.name.startswith("_")):
        results = exp / "results"
        if not results.is_dir():
            continue

        metrics = None
        for candidate in (results / "compare" / "metrics.json", results / "metrics.json"):
            if candidate.is_file():
                try:
                    metrics = json.loads(candidate.read_text(encoding="utf-8-sig"))
                except json.JSONDecodeError:
                    continue
                break

        row = {
            "experiment": exp.name,
            "title": experiment_title(exp / "README.md"),
            "frames": "",
            "psnr": "",
            "ssim": "",
        }

        if isinstance(metrics, list) and metrics:
            psnrs = [m.get("psnr") for m in metrics if isinstance(m.get("psnr"), (int, float))]
            ssims = [m.get("ssim") for m in metrics if isinstance(m.get("ssim"), (int, float))]
            row["frames"] = str(len(metrics))
            if psnrs:
                row["psnr"] = f"{sum(psnrs) / len(psnrs):.3f}"
            if ssims:
                row["ssim"] = f"{sum(ssims) / len(ssims):.4f}"
        elif isinstance(metrics, dict):
            if isinstance(metrics.get("psnr"), (int, float)):
                row["psnr"] = f"{metrics['psnr']:.3f}"
            if isinstance(metrics.get("ssim"), (int, float)):
                row["ssim"] = f"{metrics['ssim']:.4f}"
            row["frames"] = "1"

        rows.append(row)
    return rows


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Summarize experiment metrics.")
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--out", type=Path, default=None, help="write markdown here (default: stdout)")
    args = parser.parse_args(argv)

    rows = gather(args.repo_root)
    lines = ["# Experiment report", ""]
    if not rows:
        lines.append("_No experiments with results yet._")
    else:
        lines.append("| experiment | question | frames | PSNR (dB) | SSIM |")
        lines.append("|---|---|---|---|---|")
        for r in rows:
            lines.append(f"| {r['experiment']} | {r['title']} | {r['frames']} | {r['psnr']} | {r['ssim']} |")
    lines.append("")
    lines.append("_Generated by analysis/run_report.py — results/ is gitignored, so this file is a snapshot._")
    text = "\n".join(lines)

    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text, encoding="utf-8")
        print(f"wrote {args.out}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
