# script that declares a *parameter* with the same name (e.g. -FalcorDir) will
# silently overwrite the caller's argument. Scripts that take such a parameter
# must capture it before dot-sourcing; see tools/sync-passes.ps1.
$script:FalcorDir = Join-Path $EidolonRoot 'vendor\falcor'
# Pinned Falcor release. Live in one place so scripts and docs cannot drift.
