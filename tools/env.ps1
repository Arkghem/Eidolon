<#
.SYNOPSIS
    Shared constants and helpers for Eidolon tooling.

.DESCRIPTION
    Dot-source this file from any other script in tools/:

        . "$PSScriptRoot\env.ps1"

    It never changes the caller's working directory and never exits the process.
    Written for Windows PowerShell 5.1 (the default shell on this machine) so it
    also runs unchanged under PowerShell 7.
#>

$script:EidolonRoot = Split-Path -Parent $PSScriptRoot
