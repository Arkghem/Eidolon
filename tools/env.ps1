<#
.SYNOPSIS
    Write a text file as UTF-8 *without* a BOM.

.DESCRIPTION
    Set-Content -Encoding utf8 adds a BOM under Windows PowerShell 5.1, which
    breaks tools that do not expect one (CMake is tolerant, but git diffs and
    other tooling get noisy). PS7's utf8NoBOM is not available here, so we go
    through .NET directly.
#>
function Write-Utf8NoBom {
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [Parameter(Mandatory = $true)][AllowEmptyString()][string]$Content
    )
    $dir = Split-Path -Parent $Path
    if ($dir -and -not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($Path, $Content, $utf8NoBom)
}

<#
.SYNOPSIS
    Throw with a readable message when a required path is missing.
#>
function Assert-Path {
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [string]$Hint = ''
    )
    if (-not (Test-Path $Path)) {
        $msg = "Missing required path: $Path"
        if ($Hint) { $msg += "`n  hint: $Hint" }
        throw $msg
    }
}

<#
.SYNOPSIS
    Resolve a scene argument to an absolute path where possible.

.DESCRIPTION
    Falcor is launched with its working directory set to the build's bin folder,
    so a scene written as `media\Arcade\Arcade.pyscene` (the path used in Falcor's
    own docs) would be looked up relative to bin and fail. Media lives under
    vendor\falcor\media, which is exactly one hop away.

    Resolution order:
      1. the path itself (absolute, or relative to the current directory)
      2. relative to the repo root
      3. relative to vendor\falcor  (this is the `media\...` case)

    When nothing matches, the string is returned unchanged so Falcor's own search
    paths (FALCOR_MEDIA_FOLDERS) still get a chance.
#>
function Resolve-FalcorScenePath {
    param([string]$Scene)

    if ([string]::IsNullOrWhiteSpace($Scene)) { return $null }

    $candidates = @()
    if ([System.IO.Path]::IsPathRooted($Scene)) {
        $candidates += $Scene
    }
    else {
        $candidates += (Join-Path (Get-Location).Path $Scene)
        $candidates += (Join-Path $script:EidolonRoot $Scene)
        $candidates += (Join-Path $script:FalcorDir $Scene)
    }

    foreach ($candidate in $candidates) {
        if (Test-Path $candidate) { return (Resolve-Path $candidate).Path }
    }

    return $Scene
}

<#
.SYNOPSIS
    Point FALCOR_MEDIA_FOLDERS at the workspace asset folders, preserving any
    folders the user already registered.
#>
function Set-FalcorMediaFolders {
    $folders = @(
        (Join-Path $script:EidolonRoot 'assets\scenes')
        (Join-Path $script:EidolonRoot 'assets\envmaps')
    ) | Where-Object { Test-Path $_ }

    $existing = $env:FALCOR_MEDIA_FOLDERS
    if ($existing) {
        foreach ($f in ($existing -split ';')) {
            if ($f -and ($folders -notcontains $f)) { $folders += $f }
        }
    }
    $env:FALCOR_MEDIA_FOLDERS = ($folders -join ';')
    return $env:FALCOR_MEDIA_FOLDERS
}

<#
.SYNOPSIS
    Run a native command and throw when it fails, echoing the command line first.
#>
function Invoke-Native {
    param(
        [Parameter(Mandatory = $true)][string]$Exe,
        [string[]]$Arguments = @(),
        [string]$WorkingDirectory
    )
    $display = "$Exe $($Arguments -join ' ')"
    Write-Host "   > $display" -ForegroundColor DarkGray
    $push = $false
    if ($WorkingDirectory) { Push-Location $WorkingDirectory; $push = $true }
    try {
        & $Exe @Arguments
        $code = $LASTEXITCODE
    }
    finally {
        if ($push) { Pop-Location }
    }
    if ($code -ne 0) { throw "Command failed (exit $code): $display" }
    return $code
}
